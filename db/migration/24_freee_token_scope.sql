-- ============================================================
-- freee トークンに付与スコープを保存する
-- ------------------------------------------------------------
-- 打刻APIが 403「アクセス権限がありません」で弾かれるとき、
-- 原因はたいてい「そのスコープが認可されていない」こと。
--
-- freee はトークン発行時のレスポンスに scope を返すので、
-- それを保存しておけば「実際に何が許可されているか」を
-- 診断画面で確認できる。要求したスコープとの差分が分かる。
--
-- 実行場所: 移行先(DX側) SQL Editor で1回
-- ============================================================

ALTER TABLE nippo.freee_tokens
  ADD COLUMN IF NOT EXISTS scope text;

